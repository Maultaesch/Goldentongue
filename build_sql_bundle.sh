#!/usr/bin/env bash
# Builds two files you can paste into the Supabase SQL editor (no CLI needed):
#   supabase/bundle/1_schema.sql   all migrations in order (tables, security, functions)
#   supabase/bundle/2_content_lines.sql  starter data and the 325 pickup lines
#   supabase/bundle/3_content_more.sql   50 openers, 50 flirts, exercises, sections
set -euo pipefail
cd "$(dirname "$0")/../supabase"
mkdir -p bundle
{ echo "-- GoldenTongue schema. Run ONCE in Supabase > SQL Editor. Generated by scripts/build_sql_bundle.sh"
  for f in migrations/*.sql; do printf '\n-- ===== %s =====\n' "$f"; cat "$f"; done; } > bundle/1_schema.sql
{ echo "-- GoldenTongue content part 1 (325 pickup lines). Run after 1_schema.sql."; cat seed.sql; printf '\n'; cat seed_line_library.sql; } > bundle/2_content_lines.sql
{ echo "-- GoldenTongue content part 2 (openers, flirts, exercises, sections). Run after part 1."
  for f in seed_curated seed_exercises seed_sections; do printf '\n-- ===== %s.sql =====\n' "$f"; cat "$f.sql"; done; } > bundle/3_content_more.sql
wc -c bundle/*.sql
